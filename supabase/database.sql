-- 1. Table des profils (étendant auth.users)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT NOT NULL,
    full_name TEXT,
    role TEXT NOT NULL DEFAULT 'client' CHECK (role IN ('client', 'admin')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Table des produits (catalogue de machines)
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL CHECK (category IN (
        'Matériels de transformation agro-alimentaire', 
        'Matériels de BTP & Hôpitaux / Construction métallique', 
        'Matériels de Menuiserie & Boulangerie', 
        'Matériels de Spécialités'
    )),
    subcategory TEXT NOT NULL CHECK (subcategory IN (
        'Matériels de production d''Huile', 
        'Matériels de transformation de Manioc', 
        'Matériels de transformation de jus d''ananas', 
        'Matériels de transformation d''Arachide', 
        'Matériels de transformation de Karité', 
        'Matériels de transformation de Riz', 
        'Matériels de BTP', 
        'Matériels des Hôpitaux', 
        'Construction métallique', 
        'Matériels de Menuiserie', 
        'Matériels de Boulangerie', 
        'Equipement de Bureaux', 
        'Matériels de Transport & Divers', 
        'Matériels de provenderie', 
        'Moto-presse de Jus de canne à sucre'
    )),
    description TEXT,
    price_fcfa INTEGER NOT NULL,
    price_eur INTEGER NOT NULL,
    availability TEXT NOT NULL DEFAULT 'En stock',
    image_url TEXT,
    specs JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Table des commandes / demandes de devis (sans frais de livraison)
CREATE TABLE IF NOT EXISTS public.orders (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    client_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    client_name TEXT NOT NULL,
    email TEXT,
    phone TEXT NOT NULL,
    company TEXT,
    country TEXT NOT NULL,
    address TEXT NOT NULL,
    notes TEXT,
    subtotal_fcfa BIGINT NOT NULL,
    total_fcfa BIGINT NOT NULL,
    total_eur INTEGER NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'manufacturing', 'shipped', 'delivered')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Table des articles de commande
CREATE TABLE IF NOT EXISTS public.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id UUID NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES public.products(id) ON DELETE SET NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    price_fcfa INTEGER NOT NULL,
    price_eur INTEGER NOT NULL
);

-- 5. Table des messages de contact
CREATE TABLE IF NOT EXISTS public.messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT,
    phone TEXT NOT NULL,
    country TEXT NOT NULL,
    subject TEXT NOT NULL,
    message TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'unread' CHECK (status IN ('unread', 'read')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 6. Table des paramètres généraux du site
CREATE TABLE IF NOT EXISTS public.settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==========================================
-- CONFIGURATION DES PROFILE AUTOMATIQUES VIA TRIGGER
-- ==========================================

-- Fonction pour insérer automatiquement un profil lors de la création d'un utilisateur dans Supabase Auth
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger AS $$
BEGIN
  INSERT INTO public.profiles (id, email, full_name, role)
  VALUES (
    new.id,
    new.email,
    COALESCE(new.raw_user_meta_data->>'full_name', ''),
    -- Par défaut l'utilisateur est client, sauf si l'email se termine par @bevulta.com
    CASE 
      WHEN new.email LIKE '%@bevulta.com' THEN 'admin'
      ELSE 'client'
    END
  );
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger de création de profil
CREATE OR REPLACE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- ==========================================
-- FONCTION UTILITAIRE POUR RLS (ÉVITE LA RÉCURSION)
-- ==========================================

CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1 FROM public.profiles 
    WHERE id = auth.uid() AND role = 'admin'
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

