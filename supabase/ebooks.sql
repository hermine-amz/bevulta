-- =======================================================
-- TABLE DES E-BOOKS & PACKS NUMÉRIQUES - BEVULTA
-- =======================================================

CREATE TABLE IF NOT EXISTS public.ebooks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    subtitle TEXT,
    description TEXT,
    category TEXT NOT NULL,
    is_pack BOOLEAN NOT NULL DEFAULT false,
    included_books JSONB NOT NULL DEFAULT '[]'::jsonb,
    price_fcfa INTEGER NOT NULL,
    price_eur INTEGER NOT NULL,
    promo_price_fcfa INTEGER DEFAULT NULL,
    promo_price_eur INTEGER DEFAULT NULL,
    pages TEXT,
    file_format TEXT DEFAULT 'PDF Haute Définition',
    language TEXT DEFAULT 'Français',
    author TEXT DEFAULT 'Bureau d''Études BEVULTA',
    badge TEXT,
    cover_image TEXT,
    download_url TEXT,
    is_visible BOOLEAN NOT NULL DEFAULT true,
    featured BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==========================================
-- POLITIQUES RLS (ROW LEVEL SECURITY)
-- ==========================================

ALTER TABLE public.ebooks ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Tout le monde peut voir les e-books." ON public.ebooks;
CREATE POLICY "Tout le monde peut voir les e-books." ON public.ebooks
    FOR SELECT USING (true);

DROP POLICY IF EXISTS "Seuls les administrateurs peuvent insérer/modifier/supprimer les e-books." ON public.ebooks;
CREATE POLICY "Seuls les administrateurs peuvent insérer/modifier/supprimer les e-books." ON public.ebooks
    FOR ALL USING (public.is_admin());

